// The e-ticket: what it says (ticketContent, pure and easy to test) and how it looks (renderTicketPdf).
// Generated on demand from the database rather than stored, so it always shows the current status
// (after Phase 9, a passenger's RAC/WL can move to a berth; the next download shows it).

import PDFDocument from "pdfkit";
import type { CoachClass } from "../../generated/prisma/client.js";
import type { toBookingView } from "./bookings.service.js";

export type BookingView = ReturnType<typeof toBookingView>;

const CLASS_NAMES: Record<CoachClass, string> = {
    SL: "Sleeper (SL)", AC3: "AC 3 Tier (3A)", AC2: "AC 2 Tier (2A)", AC1: "AC First Class (1A)", CC: "AC Chair Car (CC)",
};

// 114600 paise → "Rs. 1,146.00" (Indian digit grouping). "Rs." because PDF's built-in fonts have no ₹ glyph.
export const rupees = (paise: number) =>
    "Rs. " + (paise / 100).toLocaleString("en-IN", { minimumFractionDigits: 2, maximumFractionDigits: 2 });

// "CNF B1/23 LOWER", "RAC 3", "WL 12": the way Indian Railways writes a passenger's status.
export function passengerStatus(p: BookingView["passengers"][number]): string {
    switch (p.status) {
        case "CONFIRMED": return p.berth ? `CNF ${p.berth.coach}/${p.berth.number} ${p.berth.type.replace("_", " ")}` : "CNF";
        case "RAC": return `RAC ${p.racNumber}`;
        case "WAITLISTED": return `WL ${p.waitlistNumber}`;
        case "CANCELLED": return "CAN";
    }
}

export interface TicketContent {
    title: string;
    journey: [label: string, value: string][];
    passengers: { no: number; name: string; age: number; gender: string; status: string }[];
    totals: [label: string, value: string][];
}

export function ticketContent(booking: BookingView, paymentId: string | null): TicketContent {
    const { from, to } = booking;
    return {
        title: `E-ticket · PNR ${booking.pnr}`,
        journey: [
            ["PNR", booking.pnr],
            ["Train", `${booking.train.number} ${booking.train.name}`],
            ["Class", CLASS_NAMES[booking.class]],
            ["Quota", booking.quota.replace("_", " ")],
            ["From", `${from.station.name} (${from.station.code})`],
            ["Departure", `${from.departure.date} ${from.departure.time}`],
            ["To", `${to.station.name} (${to.station.code})`],
            ["Arrival", `${to.arrival.date} ${to.arrival.time}`],
        ],
        passengers: booking.passengers.map((p) => ({
            no: p.position, name: p.name, age: p.age, gender: p.gender, status: passengerStatus(p),
        })),
        totals: [
            ["Total fare", rupees(booking.totalFare)],
            ["Payment", paymentId ?? "-"],
            ["Booked at", booking.createdAt.toISOString().replace("T", " ").slice(0, 16) + " UTC"],
        ],
    };
}

// pdfkit writes the document as a stream; collect it into one Buffer for a download or an attachment.
export function renderTicketPdf(content: TicketContent): Promise<Buffer> {
    const doc = new PDFDocument({ size: "A4", margin: 50, info: { Title: content.title, Author: "IRCTC Backend (test mode)" } });
    const chunks: Buffer[] = [];
    doc.on("data", (chunk: Buffer) => chunks.push(chunk));
    const done = new Promise<Buffer>((resolve, reject) => {
        doc.on("end", () => resolve(Buffer.concat(chunks)));
        doc.on("error", reject);
    });

    const left = doc.page.margins.left;
    const width = doc.page.width - left - doc.page.margins.right;

    doc.font("Helvetica-Bold").fontSize(18).text("Electronic Reservation Slip");
    doc.font("Helvetica").fontSize(9).fillColor("#b3261e")
        .text("TEST MODE: generated by a development build. Not valid for travel.");
    doc.fillColor("black").moveDown();

    // Label / value pairs in two columns.
    const pairs = (rows: [string, string][]) => {
        for (const [label, value] of rows) {
            const y = doc.y;
            doc.font("Helvetica").fontSize(10).fillColor("#555").text(label, left, y, { width: 120 });
            doc.font("Helvetica-Bold").fillColor("black").text(value, left + 130, y, { width: width - 130 });
            doc.moveDown(0.3);
        }
    };
    pairs(content.journey);

    doc.moveDown().font("Helvetica-Bold").fontSize(12).text("Passengers", left);
    doc.moveDown(0.4);
    const columns = [{ x: 0, w: 30 }, { x: 30, w: 200 }, { x: 230, w: 50 }, { x: 280, w: 90 }, { x: 370, w: width - 370 }];
    const row = (cells: string[], bold: boolean) => {
        const y = doc.y;
        doc.font(bold ? "Helvetica-Bold" : "Helvetica").fontSize(10);
        cells.forEach((cell, i) => doc.text(cell, left + columns[i].x, y, { width: columns[i].w }));
        doc.moveDown(0.4);
    };
    row(["#", "Name", "Age", "Gender", "Status"], true);
    for (const p of content.passengers) row([String(p.no), p.name, String(p.age), p.gender, p.status], false);

    doc.moveDown();
    pairs(content.totals);

    doc.moveDown().font("Helvetica").fontSize(8).fillColor("#555").text(
        "CNF = confirmed berth (coach/berth). RAC = shares a berth, may be upgraded. WL = waitlisted. " +
        "Carry a government photo ID. Download the ticket again before travel for the latest status.",
        left, doc.y, { width },
    );

    doc.end();
    return done;
}
